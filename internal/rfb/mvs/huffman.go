const huffmanLookupBits = 10

var huffmanLookup [1 << huffmanLookupBits]uint16

func init() {
	for prefix := range len(huffmanLookup) {
		symbol, length, found := decodeHuffmanCode(uint32(prefix)<<(16-huffmanLookupBits), huffmanLookupBits)
		if found {
			huffmanLookup[prefix] = uint16(symbol) | uint16(length)<<8
		}
	}
}

func decodeHuffmanCode(window uint32, maxLength uint) (symbol uint8, length uint, found bool) {
	var firstCode uint32
	valueIndex := 0
	for length = 1; length <= maxLength; length++ {
		code := window >> (16 - length)
		count := uint32(luminanceACCounts[length])
		if code >= firstCode && code < firstCode+count {
			return luminanceACValues[valueIndex+int(code-firstCode)], length, true
		}
		valueIndex += int(count)
		firstCode = (firstCode + count) << 1
	}
	return 0, 0, false
}

func readHuffmanSymbol(r *bitReader) uint8 {
	window := r.peek(16)
	entry := huffmanLookup[window>>(16-huffmanLookupBits)]
	if entry != 0 {
		r.skip(uint(entry >> 8))
		return uint8(entry)
	}
	symbol, length, found := decodeHuffmanCode(window, 16)
	if !found {
		r.invalid = true
		return 0
	}
	r.skip(length)
	return symbol
}
